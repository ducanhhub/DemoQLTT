CREATE DATABASE IF NOT EXISTS QL_TuThien
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE QL_TuThien;
SET FOREIGN_KEY_CHECKS = 0;

-- 1. Xóa toàn bộ các bảng cũ nếu đã tồn tại
DROP TABLE IF EXISTS THAM_GIA;
DROP TABLE IF EXISTS GIA_NHAP;
DROP TABLE IF EXISTS QUYEN_GOP;
DROP TABLE IF EXISTS GIAI_NGAN_PHAT_HANG;
DROP TABLE IF EXISTS HO_SO_CUU_TRO;
DROP TABLE IF EXISTS CHIEN_DICH;
DROP TABLE IF EXISTS NGUOI_DIEU_HANH;
DROP TABLE IF EXISTS KE_TOAN;
DROP TABLE IF EXISTS TINH_NGUYEN_VIEN;
DROP TABLE IF EXISTS TINH_NGUYEN_VIEN_KVHDONG;
DROP TABLE IF EXISTS NHA_HAO_TAM_SDT;
DROP TABLE IF EXISTS NHA_HAO_TAM;
DROP TABLE IF EXISTS NGUOI_THU_HUONG_SDT;
DROP TABLE IF EXISTS NGUOI_THU_HUONG;
DROP TABLE IF EXISTS NGUOI_DUNG_SDT;
DROP TABLE IF EXISTS NGUOI;

-- 2. Bảng NGUOI (Chỉ dành cho Nhân sự: BDH/NDH, Kế toán, TNV)
CREATE TABLE NGUOI (
    CCCD VARCHAR(12) PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    Email VARCHAR(100),
    DiaChi VARCHAR(200)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 2.1 Bảng NGUOI_DUNG_SDT
CREATE TABLE NGUOI_DUNG_SDT (
    CCCD VARCHAR(12) NOT NULL,
    SDT VARCHAR(15) NOT NULL,
    PRIMARY KEY (CCCD, SDT),
    CONSTRAINT FK_NGUOISDT_NGUOI FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 3. Bảng NGUOI_DIEU_HANH (Subtype 1)
CREATE TABLE NGUOI_DIEU_HANH (
    MaBDH VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NOT NULL UNIQUE,
    ChucVu VARCHAR(50),
    QuyenHanCapDuyet VARCHAR(50),
    NamBatDau INT, 
    NamKetThuc INT,
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 4. Bảng KE_TOAN (Subtype 2)
CREATE TABLE KE_TOAN (
    MaKT VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NOT NULL UNIQUE,
    TrinhDoChuyenMon VARCHAR(50),
    ViTriChuyenTrach VARCHAR(50),
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 5. Bảng TINH_NGUYEN_VIEN (Subtype 3)
CREATE TABLE TINH_NGUYEN_VIEN (
    MaTNV VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NOT NULL UNIQUE,
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 5.1 Bảng TINH_NGUYEN_VIEN_KVHDONG
CREATE TABLE TINH_NGUYEN_VIEN_KVHDONG (
    MaTNV VARCHAR(20) NOT NULL,
    KVHoatDong VARCHAR(100) NOT NULL,
    PRIMARY KEY (MaTNV, KVHoatDong),
    CONSTRAINT FK_KVHD_TNV FOREIGN KEY (MaTNV) REFERENCES TINH_NGUYEN_VIEN(MaTNV) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 6. Bảng NHA_HAO_TAM (Độc lập, bỏ cột SDT)
CREATE TABLE NHA_HAO_TAM (
    MaNHT VARCHAR(20) PRIMARY KEY,
    TenNHT VARCHAR(150) NOT NULL,
    LoaiNHT VARCHAR(30) CHECK (LoaiNHT IN ('CaNhan', 'ToChuc', 'AnDanh')),
    MaSoThue VARCHAR(20) NULL,
    Email VARCHAR(100) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 6.1 Bảng NHA_HAO_TAM_SDT (Tách thuộc tính đa trị SDT - Chuẩn 1NF)
CREATE TABLE NHA_HAO_TAM_SDT (
    MaNHT VARCHAR(20) NOT NULL,
    SDT VARCHAR(15) NOT NULL,
    PRIMARY KEY (MaNHT, SDT),
    CONSTRAINT FK_NHTSDT_NHT FOREIGN KEY (MaNHT) REFERENCES NHA_HAO_TAM(MaNHT) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 7. Bảng CHIEN_DICH
CREATE TABLE CHIEN_DICH (
    MaCD VARCHAR(20) PRIMARY KEY,
    MaBDH VARCHAR(20) NOT NULL,
    TenChienDich VARCHAR(200) NOT NULL,
    LoaiChienDich VARCHAR(50),
    MucTieuTien DECIMAL(18,2) DEFAULT 0,
    NgayBatDau DATE,
    NgayKetThuc DATE,
    TrangThai VARCHAR(50) DEFAULT 'Đang thực hiện',
    FOREIGN KEY (MaBDH) REFERENCES NGUOI_DIEU_HANH(MaBDH) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 8. Bảng THAM_GIA (Liên kết N-N)
CREATE TABLE THAM_GIA (
    MaBDH VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaTNV VARCHAR(20) NOT NULL,
    PRIMARY KEY (MaBDH, MaCD, MaTNV),
    CONSTRAINT FK_THAMGIAP_BDH FOREIGN KEY (MaBDH) REFERENCES NGUOI_DIEU_HANH(MaBDH) ON UPDATE CASCADE,
    CONSTRAINT FK_THAMGIAP_CD FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    CONSTRAINT FK_THAMGIAP_TNV FOREIGN KEY (MaTNV) REFERENCES TINH_NGUYEN_VIEN(MaTNV) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 9. Bảng GIA_NHAP (Liên kết N-N giữa KE_TOAN và CHIEN_DICH)
CREATE TABLE GIA_NHAP (
    MaBDH VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaKT VARCHAR(20) NOT NULL,
    PRIMARY KEY (MaBDH, MaCD, MaKT),
    CONSTRAINT FK_GIANHAP_BDH FOREIGN KEY (MaBDH) REFERENCES NGUOI_DIEU_HANH(MaBDH) ON UPDATE CASCADE,
    CONSTRAINT FK_GIANHAP_CD FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    CONSTRAINT FK_GIANHAP_KT FOREIGN KEY (MaKT) REFERENCES KE_TOAN(MaKT) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 10. Bảng QUYEN_GOP
CREATE TABLE QUYEN_GOP (
    MaQG VARCHAR(20) PRIMARY KEY,
    MaNHT VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaKT VARCHAR(20) NULL,
    NgayQuyenGop DATETIME DEFAULT CURRENT_TIMESTAMP,
    HinhThuc VARCHAR(30) CHECK (HinhThuc IN ('TienMat', 'ChuyenKhoan', 'HienVat')),
    SoTien DECIMAL(18,2) DEFAULT 0,
    MoTaHienVat VARCHAR(500),
    MaGiaoDichNganHang VARCHAR(50),
    TrangThaiDoiSoat VARCHAR(50) DEFAULT 'Chờ đối soát',
    FOREIGN KEY (MaNHT) REFERENCES NHA_HAO_TAM(MaNHT) ON UPDATE CASCADE,
    FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    FOREIGN KEY (MaKT) REFERENCES KE_TOAN(MaKT) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 11. Bảng NGUOI_THU_HUONG
CREATE TABLE NGUOI_THU_HUONG (
    MaNTH VARCHAR(20) PRIMARY KEY,   
    CCCD VARCHAR(12) NULL UNIQUE,
    HoTen VARCHAR(100) NOT NULL,
    DiaChi VARCHAR(200),
    HoanCanhMoTa VARCHAR(500)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 11.1 Bảng NGUOI_THU_HUONG_SDT
CREATE TABLE NGUOI_THU_HUONG_SDT (
    MaNTH VARCHAR(20) NOT NULL,
    SDT VARCHAR(15) NOT NULL,
    PRIMARY KEY (MaNTH, SDT),
    CONSTRAINT FK_NTHSDT_NTH FOREIGN KEY (MaNTH) REFERENCES NGUOI_THU_HUONG(MaNTH) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 12. Bảng HO_SO_CUU_TRO
CREATE TABLE HO_SO_CUU_TRO (
    MaHS VARCHAR(20) PRIMARY KEY,
    MaNTH VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaBDH VARCHAR(20) NULL,
    NgayNop DATE,
    SoTienDeXuat DECIMAL(18,2) DEFAULT 0,
    TrangThaiDuyet VARCHAR(50) DEFAULT 'Chờ duyệt',
    FOREIGN KEY (MaNTH) REFERENCES NGUOI_THU_HUONG(MaNTH) ON UPDATE CASCADE,
    FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    FOREIGN KEY (MaBDH) REFERENCES NGUOI_DIEU_HANH(MaBDH) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 13. Bảng GIAI_NGAN_PHAT_HANG
CREATE TABLE GIAI_NGAN_PHAT_HANG (
    MaGN VARCHAR(20) PRIMARY KEY,
    MaHS VARCHAR(20) NOT NULL,
    MaKT VARCHAR(20) NULL,
    MaTNV VARCHAR(20) NULL,
    LoaiHinh VARCHAR(30) CHECK (LoaiHinh IN ('TienMat', 'HienVat')),
    SoTienGiaiNgan DECIMAL(18,2) DEFAULT 0,
    MoTaHienVatTrao VARCHAR(500),
    NgayThucHien DATE DEFAULT (CURRENT_DATE),
    FOREIGN KEY (MaHS) REFERENCES HO_SO_CUU_TRO(MaHS) ON UPDATE CASCADE,
    FOREIGN KEY (MaKT) REFERENCES KE_TOAN(MaKT) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (MaTNV) REFERENCES TINH_NGUYEN_VIEN(MaTNV) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

