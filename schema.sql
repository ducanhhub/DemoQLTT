CREATE DATABASE IF NOT EXISTS QL_TuThien
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE QL_TuThien;
SET FOREIGN_KEY_CHECKS = 0;

-- 2. Xóa toàn bộ các bảng cũ nếu đã tồn tại
DROP TABLE IF EXISTS PHAN_CONG_NVIEN;
DROP TABLE IF EXISTS QUYEN_GOP;
DROP TABLE IF EXISTS GIAI_NGAN_PHAT_HANG;
DROP TABLE IF EXISTS HO_SO_CUU_TRO;
DROP TABLE IF EXISTS CHIEN_DICH;
DROP TABLE IF EXISTS BAN_DIEU_HANH;
DROP TABLE IF EXISTS KE_TOAN;
DROP TABLE IF EXISTS TINH_NGUYEN_VIEN;
DROP TABLE IF EXISTS NHA_HAO_TAM;
DROP TABLE IF EXISTS NGUOI_THU_HUONG;
DROP TABLE IF EXISTS NGUOI;
-- 2. Bảng NGUOI (Thực thể cha trừu tượng)
CREATE TABLE NGUOI (
    CCCD VARCHAR(12) PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    SDT VARCHAR(15),
    Email VARCHAR(100),
    DiaChi VARCHAR(200),
    LoaiNguoi VARCHAR(30) NOT NULL -- 'BanDieuHanh', 'KeToan', 'TinhNguyenVien', 'NhaHaoTam'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 3. Bảng BAN_DIEU_HANH (Subtype 1)
CREATE TABLE BAN_DIEU_HANH (
    MaBDH VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NOT NULL UNIQUE,
    ChucVu VARCHAR(50),
    QuyenHanCapDuyet VARCHAR(50),
    NamBatDau INT, 
    NamKetThuc INT,
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 4. Bảng KE_TOAN (Subtype 2)
CREATE TABLE KE_TOAN (
    MaKT VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NOT NULL UNIQUE,
    TrinhDoChuyenMon VARCHAR(50),
    ViTriChuyenTrach VARCHAR(50),
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 5. Bảng TINH_NGUYEN_VIEN (Subtype 3)
CREATE TABLE TINH_NGUYEN_VIEN (
    MaTNV VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NOT NULL UNIQUE,
    KhuVucHoatDongChinh VARCHAR(100),
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 6. Bảng NHA_HAO_TAM (Subtype 4)
CREATE TABLE NHA_HAO_TAM (
    MaNHT VARCHAR(20) PRIMARY KEY,
    CCCD VARCHAR(12) NULL UNIQUE, -- Nullable nếu là Tổ chức/Ẩn danh	
    LoaiNHT VARCHAR(30) CHECK (LoaiNHT IN ('CaNhan', 'ToChuc', 'AnDanh')),
    MaSoThue VARCHAR(20),
    FOREIGN KEY (CCCD) REFERENCES NGUOI(CCCD) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 7. Bảng CHIEN_DICH
CREATE TABLE CHIEN_DICH (
    MaCD VARCHAR(20) PRIMARY KEY,
    MaBDH VARCHAR(20) NOT NULL,
    TenChienDich VARCHAR(200) NOT NULL,
    LoaiChienDich VARCHAR(50),
    MucTieuTien DECIMAL(18,2) DEFAULT 0,
    NgayBatDau DATE,
    NgayKetThuc DATE,
    TrangThai VARCHAR(50) DEFAULT 'Đang thực hiện',
    FOREIGN KEY (MaBDH) REFERENCES BAN_DIEU_HANH(MaBDH) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 8. Bảng PHAN_CONG_NVIEN (Trung gian N - N)
CREATE TABLE PHAN_CONG_NVIEN (
    MaPC VARCHAR(20) PRIMARY KEY,
    MaBDH VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaTNV VARCHAR(20) NULL,
    MaKT VARCHAR(20) NULL,
    FOREIGN KEY (MaBDH) REFERENCES BAN_DIEU_HANH(MaBDH) ON UPDATE CASCADE,
    FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    FOREIGN KEY (MaTNV) REFERENCES TINH_NGUYEN_VIEN(MaTNV) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (MaKT) REFERENCES KE_TOAN(MaKT) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 9. Bảng QUYEN_GOP
CREATE TABLE QUYEN_GOP (
    MaQG VARCHAR(20) PRIMARY KEY,
    MaNHT VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaKT VARCHAR(20) NULL,
    NgayQuyenGop DATETIME DEFAULT CURRENT_TIMESTAMP,
    HinhThuc VARCHAR(30) CHECK (HinhThuc IN ('TienMat', 'ChuyenKhoan', 'HienVat')),
    SoTien DECIMAL(18,2) DEFAULT 0,
    MoTaHienVat VARCHAR(500),
    MaGiaoDichNganHang VARCHAR(50),
    TrangThaiDoiSoat VARCHAR(50) DEFAULT 'Chờ đối soát',
    FOREIGN KEY (MaNHT) REFERENCES NHA_HAO_TAM(MaNHT) ON UPDATE CASCADE,
    FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    FOREIGN KEY (MaKT) REFERENCES KE_TOAN(MaKT) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 10. Bảng NGUOI_THU_HUONG
CREATE TABLE NGUOI_THU_HUONG (
    MaNTH VARCHAR(20) PRIMARY KEY,   
    CCCD VARCHAR(12) NULL UNIQUE,
    HoTen VARCHAR(100) NOT NULL,
    SDT VARCHAR(15),
    DiaChi VARCHAR(200),
    HoanCanhMoTa VARCHAR(500)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 11. Bảng HO_SO_CUU_TRO
CREATE TABLE HO_SO_CUU_TRO (
    MaHS VARCHAR(20) PRIMARY KEY,
    MaNTH VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaBDH VARCHAR(20) NULL,
    NgayNop DATE DEFAULT (CURRENT_DATE),
    SoTienDeXuat DECIMAL(18,2) DEFAULT 0,
    TrangThaiDuyet VARCHAR(50) DEFAULT 'Chờ duyệt',
    FOREIGN KEY (MaNTH) REFERENCES NGUOI_THU_HUONG(MaNTH) ON UPDATE CASCADE,
    FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    FOREIGN KEY (MaBDH) REFERENCES BAN_DIEU_HANH(MaBDH) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 12. Bảng GIAI_NGAN_PHAT_HANG
CREATE TABLE GIAI_NGAN_PHAT_HANG (
    MaGN VARCHAR(20) PRIMARY KEY,
    MaHS VARCHAR(20) NOT NULL,
    MaCD VARCHAR(20) NOT NULL,
    MaKT VARCHAR(20) NULL,
    MaTNV VARCHAR(20) NULL,
    LoaiHinh VARCHAR(30) CHECK (LoaiHinh IN ('TienMat', 'HienVat')),
    SoTienGiaiNgan DECIMAL(18,2) DEFAULT 0,
    MoTaHienVatTrao VARCHAR(500),
    NgayThucHien DATE DEFAULT (CURRENT_DATE),
    FOREIGN KEY (MaHS) REFERENCES HO_SO_CUU_TRO(MaHS) ON UPDATE CASCADE,
    FOREIGN KEY (MaCD) REFERENCES CHIEN_DICH(MaCD) ON UPDATE CASCADE,
    FOREIGN KEY (MaKT) REFERENCES KE_TOAN(MaKT) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (MaTNV) REFERENCES TINH_NGUYEN_VIEN(MaTNV) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
SET FOREIGN_KEY_CHECKS = 1;


